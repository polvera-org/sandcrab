// Turns schema/server-api.schema.json (a copy of the Rust snapshot
// crates/sandcrab-protocol/tests/snapshots/server-api.schema.json) into src/generated/api.ts.
//
//   node scripts/generate-types.mjs           write the file
//   node scripts/generate-types.mjs --check   exit 1 when the committed file is stale
//
// The schema uses a small subset of JSON Schema (objects, arrays, string enums, `$ref`,
// `type: [T, "null"]`, `anyOf` with null), so this needs no dependency.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const SCHEMA_PATH = fileURLToPath(new URL("../schema/server-api.schema.json", import.meta.url));
export const OUTPUT_PATH = fileURLToPath(new URL("../src/generated/api.ts", import.meta.url));

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function refName(ref) {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) throw new Error(`unsupported $ref ${ref}`);
  return ref.slice(prefix.length);
}

function union(parts) {
  return [...new Set(parts)].join(" | ");
}

function primitive(t) {
  switch (t) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    default:
      throw new Error(`unsupported type ${t}`);
  }
}

/** The TypeScript type of a schema node, written inline. */
function typeOf(s, indent) {
  if (s === true || s === undefined) return "unknown";
  if (s.$ref) return refName(s.$ref);
  if (s.enum) return union(s.enum.map((v) => JSON.stringify(v)));
  if (s.oneOf || s.anyOf) return union((s.oneOf ?? s.anyOf).map((v) => typeOf(v, indent)));
  if (Array.isArray(s.type)) return union(s.type.map((t) => typeOf({ ...s, type: t }, indent)));
  if (s.type === "array") {
    const item = typeOf(s.items, indent);
    return item.includes(" ") ? `(${item})[]` : `${item}[]`;
  }
  if (s.type === "object") {
    if (s.properties) return objectBody(s, indent);
    if (s.additionalProperties && s.additionalProperties !== true) {
      return `Record<string, ${typeOf(s.additionalProperties, indent)}>`;
    }
    return "Record<string, unknown>";
  }
  if (s.type === undefined) return "unknown";
  return primitive(s.type);
}

function doc(text, indent) {
  if (!text) return "";
  const lines = text.replaceAll("*/", "*\\/").split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

function objectBody(s, indent) {
  const inner = `${indent}  `;
  const required = new Set(s.required ?? []);
  let out = "{\n";
  for (const [name, prop] of Object.entries(s.properties)) {
    const key = IDENT.test(name) ? name : JSON.stringify(name);
    out += doc(prop.description, inner);
    out += `${inner}${key}${required.has(name) ? "" : "?"}: ${typeOf(prop, inner)};\n`;
  }
  return `${out}${indent}}`;
}

function table(name, entries, row) {
  let out = `export interface ${name} {\n`;
  for (const [key, value] of Object.entries(entries)) out += `  ${JSON.stringify(key)}: ${row(value)};\n`;
  return `${out}}\n`;
}

/** The whole generated file, from the parsed schema document. */
export function generate(schema) {
  let out =
    "// Generated by scripts/generate-types.mjs from schema/server-api.schema.json. Do not edit.\n" +
    "// Wire types of the sandcrab server API: field names are the ones on the wire.\n\n";
  out += `export const API_VERSION = ${JSON.stringify(schema.api_version)};\n\n`;
  out += `export const FEATURES = ${JSON.stringify(schema.features)} as const;\n\n`;

  for (const [name, def] of Object.entries(schema.$defs)) {
    out += doc(def.description, "");
    if (def.type === "object" && def.properties) {
      out += `export interface ${name} ${objectBody(def, "")}\n\n`;
    } else {
      out += `export type ${name} = ${typeOf(def, "")};\n\n`;
    }
  }

  out += doc("Every method: `control` ones are requests on the control connection, `connection` ones are the first frame of a connection of their own.", "");
  out += table(
    "Methods",
    schema.methods,
    (m) => `{ kind: ${JSON.stringify(m.kind)}; params: ${typeOf(m.params, "  ")}; result: ${typeOf(m.result, "  ")} }`,
  );
  out += "\n" + doc("Notifications from the server, on a control connection.", "");
  out += table("Notifications", schema.notifications, (n) => typeOf(n.params, "  "));
  out += "\n" + doc("The `data` of each server error.", "");
  out += table("ErrorData", schema.errors, (e) => typeOf(e.data, "  "));
  out += "\n" + doc("JSON-RPC codes of the server's errors.", "");
  out += "export const ERROR_CODES = {\n";
  for (const [name, e] of Object.entries(schema.errors)) out += `  ${name}: ${e.code},\n`;
  out += "} as const;\n";
  out += "\n" + doc("Kind byte of the `EXIT` record; its payload is `ProcessExit` as JSON.", "");
  out += `export const RECORD_KIND_EXIT = ${schema.records.EXIT.kind};\n`;
  return out;
}

if (import.meta.main) {
  const text = generate(JSON.parse(readFileSync(SCHEMA_PATH, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT_PATH, "utf8");
    } catch {
      // Missing counts as stale.
    }
    if (current !== text) {
      console.error("src/generated/api.ts is stale: run `pnpm generate`");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT_PATH, text);
  }
}
