#!/usr/bin/env python3
"""Embed the headline benchmark numbers into docs/site/benchmarks.html (the TL;DR page).

Reads the committed results JSON in docs/bench/results/ directly and rewrites the block
between the TLDR-DATA markers in the page. The page renders every number from that block,
so nothing on it is hand-typed. The full report (docs/site/bench-report.html, generated by
scripts/bench-report-data.py) stays the place for distributions, caveats and method.

What it picks, per host and backend (template "base", warm cache):
  - lifecycle (W0): spawn_ready, teardown, first_call  -> p50, p95, n
  - agent-turn (W1): agent_turn                        -> p50, p95, n
  - resources (W1): memory per idle sandbox (one kind per backend/OS, named), idle CPU
  - density: the largest number of idle sandboxes kept alive at once, and the cap

It also checks the claims the page's "What it means" fold makes, and exits non-zero if a
new run breaks one, so the page cannot keep a conclusion its numbers no longer support.

Before writing, it runs a self-test that feeds check_claims mutated data (e.g. a fake
Firecracker idle memory below Docker's) and fails if a broken claim would get through.

Usage (from the repo root):
    python3 scripts/bench-tldr-data.py              # self-test, then write the page
    python3 scripts/bench-tldr-data.py --self-test  # self-test only
"""

from __future__ import annotations

import copy
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "docs/bench/results"
PAGE = ROOT / "docs/site/benchmarks.html"
GLYPHS = ROOT / "docs/site/assets/crab/svg"
BEGIN = "<!-- TLDR-DATA:BEGIN -->"
END = "<!-- TLDR-DATA:END -->"

# Hosts in page order. Each run is (file, role): "primary" supplies latency, resources
# and density for its available backends; "density" replaces the host's density data
# (a density-only rerun). Same files and roles as the full report.
HOSTS = (
    ("kvm-dedicated", (
        ("20261124T183907Z-kvm-dedicated.json", "primary"),
        ("20261125T014108Z-kvm-dedicated.json", "primary"),
    )),
    ("mac-m2", (
        ("20261124T222350Z-mac-m2.json", "primary"),
        ("20261125T020230Z-mac-m2.json", "density"),
    )),
    ("dev-vps", (
        ("20261123T091401Z-dev-vps.json", "primary"),
    )),
)
# Backend order inside a host (fastest-to-ready microVM first is not assumed: fixed order).
ORDER = ("libkrun", "firecracker", "docker")
# Backends a host has not measured yet: shown as "coming soon", never as numbers.
PENDING = {("mac-m2", "docker")}

LEGACY_BACKENDS = {"docker-dev": "docker"}
LEGACY_METRICS = {"cpu.helper_idle_60s": "cpu.idle_60s"}

# Memory per idle sandbox: the first measured metric wins. The label names its kind.
MEM_KINDS = (
    ("mem.cgroup_current_idle", "cgroup memory"),
    ("mem.host_pss_idle", "PSS"),
    ("mem.helper_rss_idle", "helper RSS"),
    ("mem.vmm_rss_idle", "VMM RSS"),
)


def backend_of(name: str) -> str:
    return LEGACY_BACKENDS.get(name, name)


def stats(m: dict | None) -> dict | None:
    if not m or m.get("not_measured") is not None or not m.get("stats"):
        return None
    s = m["stats"]
    return {"p50": s["p50"], "p95": s["p95"], "n": s.get("n", len(m.get("samples") or []))}


def cell(run: dict, backend: str, workspace: str, scenario: str) -> dict | None:
    for c in run["cells"]:
        if (backend_of(c["backend"]) == backend and c["template"] == "base" and c["cache"] == "warm"
                and c["workspace"] == workspace and c["scenario"] == scenario and c["status"] == "ok"):
            return c
    return None


def metric(c: dict | None, mid: str) -> dict | None:
    if c is None:
        return None
    m = c["metrics"].get(mid)
    if stats(m) is None:
        old = next((o for o, n in LEGACY_METRICS.items() if n == mid), None)
        if old:
            m = c["metrics"].get(old)
    return stats(m)


def short_cpu(model: str) -> str:
    s = re.sub(r"\((R|TM)\)", "", model)
    s = re.sub(r" CPU @.*| \d+-Core Processor.*", "", s)
    return re.sub(r"^Intel |^AMD ", "", s).strip()


def storage_kind(st: dict) -> str:
    t = (st or {}).get("type") or ""
    return "HDD" if "hdd" in t else "SSD" if "ssd" in t else t.upper()


def host_info(h: dict) -> dict:
    kind = h.get("kind")
    cpu = short_cpu(h.get("cpu_model") or "")
    st = storage_kind(h.get("storage"))
    if kind == "vm":
        label = f"{h.get('threads')}-vCPU VPS ({cpu}), {st}"
    elif cpu.startswith("Apple"):
        label = f"{cpu} laptop, {st}"
    else:
        label = f"Bare-metal {cpu}, {st}"
    return {
        "label": label, "kind": kind, "cpu": cpu, "storage": st,
        "cores": h.get("cores"), "threads": h.get("threads"),
        "mem_gib": round((h.get("mem_total_bytes") or 0) / 2**30),
    }


def density(run: dict, backend: str) -> dict | None:
    reps = [r for r in run["density"]
            if backend_of(r["backend"]) == backend and r["template"] == "base" and r["variant"] == "idle"]
    if not reps:
        return None
    return {
        "max_n": max(r["max_n"] for r in reps),
        "cap": reps[0]["cap"],
        "reps": len(reps),
        "all_capped": all(r["stop_reason"] == "cap" for r in reps),
    }


def glyph(name: str) -> str:
    svg = (GLYPHS / f"{name}.svg").read_text().strip()
    svg = re.sub(r'\sstyle="color:#[0-9A-Fa-f]+"', "", svg)
    svg = re.sub(r"<title>.*?</title>\s*", "", svg, flags=re.S)
    return svg.replace('role="img"', 'aria-hidden="true"')


def build_host(hid: str, runs: tuple) -> dict:
    loaded = [(json.loads((RESULTS / f).read_text()), f, role) for f, role in runs]
    info = None
    backends = {}
    dens_override = {}
    run_meta = []
    for d, f, role in loaded:
        if d["host"]["hostname"] != hid:
            sys.exit(f"{f}: host {d['host']['hostname']}, expected {hid}")
        info = info or host_info(d["host"])
        avail = [backend_of(b["backend"]) for b in d["backends"] if b["status"] == "available"]
        commit = d["git"]["commit"][:7] + ("-dirty" if d["git"].get("dirty") else "")
        run_meta.append({"file": f, "role": role, "date": d["started_at"][:10], "commit": commit,
                         "backends": avail})
        for b in avail:
            if role == "density":
                dens_override[b] = density(d, b)
                continue
            if b in backends:
                sys.exit(f"{hid}: backend {b} appears in two primary runs")
            life = cell(d, b, "W0", "lifecycle")
            res = cell(d, b, "W1", "resources")
            mem = next(({"bytes": s["p50"], "kind": k, "n": s["n"]}
                        for mid, k in MEM_KINDS if (s := metric(res, mid))), None)
            cpu = metric(res, "cpu.idle_60s")
            caps = next(x["capabilities"] for x in d["backends"] if backend_of(x["backend"]) == b)
            backends[b] = {
                "backend": b,
                "spawn_ready": metric(life, "spawn_ready"),
                "teardown": metric(life, "teardown"),
                "first_call": metric(life, "first_call"),
                "agent_turn": metric(cell(d, b, "W1", "agent-turn"), "agent_turn"),
                "mem_idle": mem,
                "cpu_idle": cpu and {"cpu_s": cpu["p50"], "window_s": d["config"]["idle_window_s"]},
                "shared_daemons_bytes": (sum(d["shared_overhead"].values()) or None)
                if b == "docker" and d.get("shared_overhead") else None,
                "density": density(d, b),
                "hardware_isolated": bool(caps and caps.get("hardware_isolated")),
                "multi_tenant_safe": bool(caps and caps.get("multi_tenant_safe")),
                "file": f,
            }
    for b, c in backends.items():
        if c["spawn_ready"] is None:
            sys.exit(f"{hid}: {b} has no ok lifecycle spawn_ready cell; the page cannot render it")
    for b, dn in dens_override.items():
        if b in backends and dn:
            backends[b]["density"] = dn
    cols = [backends[b] for b in ORDER if b in backends]
    cols += [{"backend": b, "pending": True} for (h, b) in sorted(PENDING) if h == hid and b not in backends]
    cols.sort(key=lambda c: ORDER.index(c["backend"]))
    return {"id": hid, **info, "backends": cols, "runs": run_meta}


def check_claims(hosts: list) -> dict:
    """The "What it means" fold. Each claim is recomputed here; a false one stops the build."""
    by = {h["id"]: {c["backend"]: c for c in h["backends"] if not c.get("pending")} for h in hosts}
    kvm, mac = by["kvm-dedicated"], by["mac-m2"]
    sp = lambda c: c["spawn_ready"]["p50"]
    fails = []
    # 1. libkrun is the fastest backend to a ready sandbox on the host that has all three.
    if not (sp(kvm["libkrun"]) < sp(kvm["firecracker"]) < sp(kvm["docker"])):
        fails.append("kvm-dedicated spawn order is not libkrun < firecracker < docker")
    # 2. Both microVMs reach ready in under a second (p95), with hardware isolation.
    for b in ("libkrun", "firecracker"):
        if not (kvm[b]["hardware_isolated"] and kvm[b]["spawn_ready"]["p95"] < 1e9):
            fails.append(f"{b} on kvm-dedicated: not hardware isolated or spawn p95 >= 1 s")
    if not (mac["libkrun"]["hardware_isolated"] and mac["libkrun"]["spawn_ready"]["p95"] < 1e9):
        fails.append("libkrun on mac-m2: not hardware isolated or spawn p95 >= 1 s")
    # 3. Docker is lighter at idle than every microVM measured on the same host (same memory
    # kind, also with its daemons). The page names exactly the microVMs in `light_vs`, so an
    # unmeasured one (no idle memory and CPU) is never implied by the claim.
    dk = kvm["docker"]
    dens_n = dk["density"]["max_n"]
    vms = [b for b in ORDER if b in kvm and kvm[b]["hardware_isolated"]]
    light_vs = []
    for b in vms:
        vm = kvm[b]
        if vm["mem_idle"] is None and vm["cpu_idle"] is None:
            continue
        light_vs.append(b)
        if vm["mem_idle"] is None or vm["cpu_idle"] is None:
            fails.append(f"{b} on kvm-dedicated has only one of idle memory/CPU measured")
            continue
        if dk["mem_idle"]["kind"] != vm["mem_idle"]["kind"]:
            fails.append(f"kvm-dedicated docker/{b} memory kinds differ")
        if not (dk["mem_idle"]["bytes"] < vm["mem_idle"]["bytes"]
                and dk["cpu_idle"]["cpu_s"] < vm["cpu_idle"]["cpu_s"]
                and dk["mem_idle"]["bytes"] * dens_n + (dk["shared_daemons_bytes"] or 0)
                < vm["mem_idle"]["bytes"] * dens_n):
            fails.append(f"docker is not lighter than {b} at idle on kvm-dedicated")
    if not light_vs:
        fails.append("no microVM on kvm-dedicated has idle memory/CPU to compare docker with")
    if dk["hardware_isolated"] or dk["multi_tenant_safe"]:
        fails.append("docker reports hardware isolation or multi-tenant safety")
    if fails:
        sys.exit("claims no longer hold:\n  " + "\n  ".join(fails))
    return {"ok": True, "fleet_n": dens_n, "light_vs": light_vs,
            "light_vs_all": light_vs == vms}


def self_test(hosts: list) -> None:
    """check_claims must reject data that breaks a claim (mutation tests on a copy)."""
    def kvm_col(hs: list, b: str) -> dict:
        h = next(h for h in hs if h["id"] == "kvm-dedicated")
        return next(c for c in h["backends"] if c["backend"] == b)

    def rejects(mutate) -> bool:
        hs = copy.deepcopy(hosts)
        mutate(hs)
        try:
            check_claims(hs)
        except SystemExit:
            return True
        return False

    def fake_fc(hs: list, mem: bool, cpu: bool) -> None:
        fc, dk = kvm_col(hs, "firecracker"), kvm_col(hs, "docker")
        if mem:
            fc["mem_idle"] = {"bytes": 1 << 20, "kind": dk["mem_idle"]["kind"], "n": 10}
        if cpu:
            fc["cpu_idle"] = {"cpu_s": 1.0, "window_s": 60}

    base = check_claims(copy.deepcopy(hosts))
    cases = {
        # The case the review found: a microVM lighter than Docker must break claim 3.
        "firecracker idle memory 1 MiB": lambda hs: fake_fc(hs, mem=True, cpu=True),
        "firecracker idle memory only": lambda hs: fake_fc(hs, mem=True, cpu=False),
        "firecracker spawn faster than libkrun": lambda hs: kvm_col(hs, "firecracker")[
            "spawn_ready"].update(p50=1.0),
        "docker hardware isolated": lambda hs: kvm_col(hs, "docker").update(
            hardware_isolated=True),
    }
    missed = [name for name, m in cases.items() if not rejects(m)]
    if missed:
        sys.exit("self-test: check_claims accepted broken data: " + ", ".join(missed))
    unmeasured = [b for b in ("firecracker",)
                  if kvm_col(hosts, b)["mem_idle"] is None and b in base["light_vs"]]
    if unmeasured:
        sys.exit(f"self-test: claim 3 names unmeasured {unmeasured}")


def main() -> None:
    hosts = [build_host(hid, runs) for hid, runs in HOSTS]
    self_test(hosts)
    if "--self-test" in sys.argv[1:]:
        print("self-test ok")
        return
    data = {
        "generator": "scripts/bench-tldr-data.py",
        "hosts": hosts,
        "claims": check_claims(hosts),
        "glyphs": {g: glyph(g) for g in ("tide-clock", "reef", "isolation")},
    }
    blob = json.dumps(data, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    block = f'{BEGIN}\n<script id="tldr-data" type="application/json">{blob}</script>\n{END}'
    html = PAGE.read_text()
    if BEGIN not in html or END not in html:
        sys.exit(f"markers missing in {PAGE}")
    pre, rest = html.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    PAGE.write_text(pre + block + post)
    print(f"embedded {len(blob):,} bytes into {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
