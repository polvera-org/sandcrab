#!/usr/bin/env python3
"""Extract the numbers shown in docs/site/presentation.html.

Reads the canonical bench results JSON, the live-check report and the
BackendCapabilities literals in the backend crates, and writes
docs/site/presentation/data.js (a classic script, so the deck also works from
file://). No number in the presentation is hand-typed.

Usage (from the repo root):
    python3 docs/site/presentation/extract-data.py
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CANONICAL = ROOT / "docs/bench/results/20261123T091401Z-dev-vps.json"
LIVE_CHECK = ROOT / "docs/bench/live-check.md"
OUT = Path(__file__).resolve().parent / "data.js"
CAPS = {
    "docker-dev": "crates/sandcrab-backend-docker/src/backend.rs",
    "firecracker": "crates/sandcrab-backend-firecracker/src/backend.rs",
}


def ms(ns: float) -> float:
    return round(ns / 1e6, 2)


def stats(cell: dict, metric: str) -> dict | None:
    m = cell["metrics"].get(metric)
    if not m or not m.get("stats"):
        return None
    s = m["stats"]
    if m["unit"] == "ns":
        return {"p50_ms": ms(s["p50"]), "p95_ms": ms(s["p95"]), "n": s["n"]}
    return {"p50": s["p50"], "p95": s["p95"], "n": s["n"], "unit": m["unit"]}


def find(cells, template, ws, scenario):
    for c in cells:
        if (c["backend"], c["template"], c["cache"], c["workspace"], c["scenario"], c["status"]) == (
            "docker-dev", template, "warm", ws, scenario, "ok"):
            return c
    sys.exit(f"cell not found: {template} {ws} {scenario}")


def rust_caps(rel: str) -> dict:
    src = (ROOT / rel).read_text()
    m = re.search(r"fn capabilities\(&self\) -> BackendCapabilities \{\s*BackendCapabilities \{(.*?)\}", src, re.S)
    if not m:
        sys.exit(f"capabilities() not found in {rel}")
    return {k: v == "true" for k, v in re.findall(r"(\w+):\s*(true|false)", m.group(1))}


def bench() -> dict:
    raw = CANONICAL.read_bytes()
    d = json.loads(raw)
    cells = d["cells"]
    life = [c for c in cells if c["backend"] == "docker-dev" and c["scenario"] == "lifecycle"
            and c["cache"] == "warm" and c["status"] == "ok"]

    def rng(metric):
        v = [stats(c, metric)["p50_ms"] for c in life if stats(c, metric)]
        return [min(v), max(v)]

    base0 = find(cells, "base", "W0", "lifecycle")
    fc = next(b for b in d["backends"] if b["backend"] == "firecracker")
    return {
        "file": str(CANONICAL.relative_to(ROOT)),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "commit": d["git"]["commit"][:7],
        "host": f'{d["host"]["cpu_model"]}, {d["host"]["cores"]} vCPU, {d["host"]["kind"]}',
        "kvm_available": d["host"]["kvm_available"],
        "lifecycle_cells": len(life),
        "n": base0["n"],
        "spawn_ready_range_ms": rng("spawn_ready"),
        "teardown_range_ms": rng("teardown"),
        "first_call_range_ms": rng("first_call"),
        "base_w0": {k: stats(base0, k) for k in ("spawn_ready", "teardown", "first_call", "call.bash_echo")},
        "agent_turn_base_w1": stats(find(cells, "base", "W1", "agent-turn"), "agent_turn"),
        "cgroup_mem_idle_bytes": stats(find(cells, "base", "W1", "resources"), "mem.cgroup_current_idle"),
        "density_max": max(x["max_n"] for x in d["density"]),
        "density_cap": d["config"]["density_cap"],
        "drift_pct": round(d["drift_check"]["drift_pct"], 1),
        "firecracker": {"status": fc["status"], "todo": fc["todo"], "reason": fc["reason"]},
    }


def live_check() -> dict:
    md = LIVE_CHECK.read_text()
    row = re.search(r"\|\s*\*\*Total\*\*\s*\|[^|]*\|\s*\*\*(\d+)m(\d+)s\*\*\s*\|\s*\*\*(\d+)\*\*\s*\|"
                    r"\s*\*\*(\d+)\*\*\s*\|\s*\*\*\$([\d.]+)\*\*", md)
    if not row:
        sys.exit("live-check Total row not found")
    turns = len(re.findall(r"^\|\s*[123]\s*\|", md, re.M))
    tools = {k: int(v) for k, v in re.findall(r"`(\w+)`\s*\|\s*(\d+)", md)}
    return {
        "wall_min": int(row.group(1)), "wall_s": int(row.group(2)),
        "model_calls": int(row.group(3)), "tool_calls": int(row.group(4)),
        "cost_usd": float(row.group(5)), "turns": turns,
        "tool_errors": int(re.search(r"\*\*Errors and retries\*\*:\s*(\d+) tool replies", md).group(1)),
        "bash_calls": tools.get("bash"),
    }


def main() -> None:
    data = {
        "generator": "docs/site/presentation/extract-data.py",
        "bench": bench(),
        "live": live_check(),
        "caps": {name: {"source": rel, **rust_caps(rel)} for name, rel in CAPS.items()},
    }
    js = ("// Generated by docs/site/presentation/extract-data.py. Do not edit by hand.\n"
          f"window.SANDCRAB_DATA = {json.dumps(data, indent=1)};\n")
    OUT.write_text(js)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
